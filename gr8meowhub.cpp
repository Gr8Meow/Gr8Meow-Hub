// Installed = what the app itself wrote to the registry (HubLink) or what the Hub installed.
static void RefreshInstalled(App& a) {
    a.installed.clear();
    a.exePath.clear();
    a.dir.clear();
    a.managed = false;
    std::wstring sub = std::wstring(kRegRoot) + L"\\Apps\\" + FromUtf8(a.def.id);
    std::wstring rexe = RegGet(sub, L"ExePath"), rver = RegGet(sub, L"Version");
    bool regOk = !rexe.empty() && IsFile(rexe);
    InstallRec* rec = FindRec(a.def.id);
    if (rec) {
        bool recExe = !rec->exe.empty() && IsFile(rec->exe);
        if (recExe) {
            a.installed = rec->ver;
            a.exePath = rec->exe;
            a.dir = rec->dir;
            a.managed = !rec->dir.empty();
        } else if (rec->exe.empty() && !regOk) {
            a.installed = rec->ver;  // installed by an .exe installer, location unknown
        }
    }
    if (regOk) {
        a.exePath = rexe;
        std::string v = ToUtf8(rver);
        if (!v.empty() && ValidTag(v)) a.installed = v;
        else if (a.installed.empty()) a.installed = "0";
    }
}

