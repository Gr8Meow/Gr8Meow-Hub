static void OnManifest(ManifestMsg* mm) {
    g_manifestOk = mm->ok;
    g_offline = mm->offline;
    std::vector<App> fresh;
    for (const AppDef& d : mm->defs) {
        App a;
        a.def = d;
        RefreshInstalled(a);
        bool seen = false;
        for (const std::string& s : g_s.seen) seen = seen || s == d.id;
        a.isNew = !g_firstRun && !seen;
        fresh.push_back(a);
    }
    if (mm->ok) {
        g_apps = fresh;
        g_s.seen.clear();
        for (const App& a : g_apps) g_s.seen.push_back(a.def.id);
        SaveSettings();
    }
    delete mm;
}

static void OnRelease(RelMsg* m) {
    App* a = FindApp(m->id);
    if (a) {
        a->relDone = true;
        a->relOk = m->ok;
        a->latest = m->tag;
        a->assetUrl = m->url;
        a->assetName = m->name;
        a->shaUrl = m->shaUrl;
        a->note = m->note;
    }
    delete m;
}

static void OnHubRelease(RelMsg* m) {
    g_hub.checked = true;
    g_hub.ok = m->ok;
    g_hub.tag = m->tag;
    g_hub.url = m->url;
    g_hub.name = m->name;
    g_hub.shaUrl = m->shaUrl;
    g_hub.newer = m->ok && CmpVer(m->tag, APP_VERSION) > 0;
    delete m;
}

static void OnFetchDone() {
    g_fetching = false;
    KillTimer(g_main, 1);
    // an app opened the Hub with --update <id>: show that app first
    App* f = FindApp(g_focusId);
    if (f) {
        size_t idx = (size_t)(f - &g_apps[0]);
        if (idx > 0) std::rotate(g_apps.begin(), g_apps.begin() + (long)idx, g_apps.begin() + (long)idx + 1);
    }
    g_footer = g_manifestOk ? L"" : L"No app list found";
    if (g_offline) g_footer = L"Offline - showing the saved app list";
}

static void OnProgress(int stage, int pct) {
    static const wchar_t* names[] = {L"Downloading", L"Verifying", L"Unpacking", L"Running installer", L"Finishing"};
    std::wstring t = names[min(max(stage, 0), 4)];
    if (stage == 0 && pct >= 0) t += L" " + std::to_wstring(pct) + L"%";
    else t += L"...";
    if (g_jobKind == 0) {
        App* a = FindApp(g_jobId);
        if (a) {
            a->progress = pct < 0 ? 0 : (stage == 0 ? pct : 100);
            a->status = t;
        }
    } else {
        g_footer = L"Updating the Hub: " + t;
    }
}

static void OnJobDone(JobResult* r) {
    g_jobRunning = false;
    if (r->kind == 0) {
        App* a = FindApp(r->id);
        if (a) {
            a->busy = false;
            a->progress = 0;
            if (r->ok) {
                SetRec(a->def.id, r->tag, r->exe, r->dir);
                SaveSettings();
                RefreshInstalled(*a);
                if (a->installed.empty()) a->installed = r->tag;
                a->status = r->msg.empty() ? L"Installed" : r->msg;
                a->failed = false;
                a->isNew = false;
            } else {
                a->status = r->msg;
                a->failed = true;
                g_updAll = false;
            }
        }
        if (g_updAll) NextUpdateAll();
        if (!g_jobRunning) g_footer = L"";
    } else {
        if (r->ok) ApplyHubUpdate(r->newHubExe);
        else {
            g_hubErr = r->msg;
            g_footer = L"Hub update failed: " + r->msg;
        }
    }
    delete r;
}

