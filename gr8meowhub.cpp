static void Button(RectF r, int id, int arg, const wchar_t* label, const char* icon, int style, bool enabled = true) {
    bool hot = enabled && IsHover(id, arg);
    Color fill = style == 1 ? (hot ? Mix(cAccent, Color(255, 255, 255), 0.25f) : cAccent) : (hot ? cCardHover : Mix(cCard, cBg, 0.45f));
    Color fg = style == 1 ? cOnAccent : cText;
    if (!enabled) {
        fill = Mix(cCard, cBg, 0.45f);
        fg = cMuted;
    }
    FillRR(r, F(12), fill);
    float tw = TextW(label, fBodyB), iw = icon ? F(20) + F(8) : 0;
    float x = r.X + (r.Width - tw - iw) / 2;
    if (icon) {
        Icon(icon, RectF(x, r.Y + (r.Height - F(20)) / 2, F(20), F(20)), fg);
        x += iw;
    }
    Text(label, fBodyB, RectF(x, r.Y, tw + F(6), r.Height), fg);
    if (enabled) AddHit(r, id, arg);
}
