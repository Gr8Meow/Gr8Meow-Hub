static bool ReadFileAll(const std::wstring& path, std::string& out, size_t maxBytes) {
    FILE* f = _wfopen(path.c_str(), L"rb");
    if (!f) return false;
    out.clear();
    char buf[4096];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        out.append(buf, n);
        if (out.size() > maxBytes) {
            fclose(f);
            return false;
        }
    }
    fclose(f);
    return true;
}
static bool WriteFileAll(const std::wstring& path, const std::string& data) {
    FILE* f = _wfopen(path.c_str(), L"wb");
    if (!f) return false;
    fwrite(data.data(), 1, data.size(), f);
    fclose(f);
    return true;
}

static bool ValidRepo(const std::string& s) {
    size_t slash = s.find('/');
    if (slash == std::string::npos || slash == 0 || slash + 1 >= s.size() || s.size() > 100) return false;
    if (s.find('/', slash + 1) != std::string::npos) return false;
    for (char c : s) {
        bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '-' || c == '_' ||
                  c == '.' || c == '/';
        if (!ok) return false;
    }
    return s.find("..") == std::string::npos;
}
