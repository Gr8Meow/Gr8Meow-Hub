// Native version of the loading animation: spinning ring, bobbing note, twinkling star.
static void DrawSpinner(float cx, float cy, float rad) {
    double t = (double)(GetTickCount64() % 1600) / 1600.0, tau = 6.283185307;
    RectF ring(cx - rad, cy - rad, rad * 2, rad * 2);
    Pen faint(Color(60, cAccent.GetR(), cAccent.GetG(), cAccent.GetB()), F(5));
    G->DrawEllipse(&faint, ring);
    float start = (float)(t * 360.0) - 90.0f;
    float sweep = 70.0f + 190.0f * (float)(0.5 - 0.5 * cos(t * tau));
    Pen p(cAccent, F(5));
    p.SetStartCap(LineCapRound);
    p.SetEndCap(LineCapRound);
    G->DrawArc(&p, ring, start, sweep);
    float bob = (float)(sin(t * tau) * F(3));
    Icon("music", RectF(cx - rad * 0.42f, cy - rad * 0.42f + bob, rad * 0.84f, rad * 0.84f), cAccent);
    float sx = cx + rad * 0.78f, sy = cy - rad * 0.78f, a = (float)(t * tau);
    PointF pts[8];
    for (int i = 0; i < 8; i++) {
        float rr = (i % 2 == 0) ? F(8) : F(3), ang = a + (float)i * 3.14159265f / 4.0f;
        pts[i] = PointF(sx + rr * cosf(ang), sy + rr * sinf(ang));
    }
    SolidBrush sb(Mix(cAccent, Color(255, 255, 255), 0.45f));
    G->FillPolygon(&sb, pts, 8);
}

