static void DrawApps(int W, int H) {
    float px = F(PAD), pw = (float)(W - 2 * S(PAD)), top = F(HEADER_H);

    std::vector<std::wstring> lines;
    bool hasUpdates = false;
    BuildBanner(lines, hasUpdates);
    if (!lines.empty()) {
        float bh = F(18) + F(20) * (float)lines.size();
        RectF b(px, top, pw, bh);
        FillRR(b, F(14), Mix(cCard, cAccent, 0.16f));
        StrokeRR(b, F(14), Mix(cCard, cAccent, 0.55f), 1.2f);
        Icon("bolt", RectF(b.X + F(16), b.Y + (bh - F(20)) / 2, F(20), F(20)), cAccent);
        float tw = pw - F(52) - (hasUpdates ? F(150) : 0);
        for (size_t i = 0; i < lines.size(); i++)
            Text(lines[i], fBody, RectF(b.X + F(48), b.Y + F(9) + F(20) * (float)i, tw, F(20)), cText);
        if (hasUpdates && !g_jobRunning && !g_fetching)
            Chip(RectF(b.X + b.Width - F(14) - F(130), b.Y + (bh - F(34)) / 2, F(130), F(34)), ID_UPDATEALL, 0, L"Update all", true);
        top += bh + F(12);
    }

    g_listRect = RectF(px, top, pw, (float)H - top - F(FOOTER_H));
    if (g_apps.empty()) {
        g_maxScroll = 0;
        DrawEmpty(g_listRect, g_fetching);
        return;
    }
    int n = (int)g_apps.size();
    float rowH = F(CARD_H), gap = F(CARD_GAP), total = n * (rowH + gap) - gap;
    g_maxScroll = (int)max(0.0f, total - g_listRect.Height + F(2));
    g_scroll = max(0, min(g_scroll, g_maxScroll));

    GraphicsState st = G->Save();
    G->SetClip(g_listRect);
    for (int i = 0; i < n; i++) {
        float ry = g_listRect.Y + i * (rowH + gap) - g_scroll;
        if (ry + rowH < g_listRect.Y || ry > g_listRect.Y + g_listRect.Height) continue;
        RectF row(g_listRect.X, ry, g_listRect.Width - (g_maxScroll > 0 ? F(12) : 0), rowH);
        size_t h0 = g_hits.size();
        DrawAppCard(i, row);
        for (size_t k = h0; k < g_hits.size(); k++) RectF::Intersect(g_hits[k].r, g_hits[k].r, g_listRect);
    }
    G->Restore(st);
    if (g_maxScroll > 0) {
        float trackH = g_listRect.Height - F(8);
        float thumbH = max(F(28), trackH * g_listRect.Height / (g_listRect.Height + (float)g_maxScroll));
        float thumbY = g_listRect.Y + F(4) + (trackH - thumbH) * (float)g_scroll / (float)g_maxScroll;
        FillRR(RectF(g_listRect.X + g_listRect.Width - F(5), thumbY, F(4), thumbH), F(2), Mix(cCard, cMuted, 0.6f));
    }
}

