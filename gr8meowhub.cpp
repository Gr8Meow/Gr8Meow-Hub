static HICON MakeAppIcon(int size) {
    Bitmap bmp(size, size, PixelFormat32bppARGB);
    Graphics g(&bmp);
    g.SetSmoothingMode(SmoothingModeAntiAlias);
    g.Clear(Color(0, 0, 0, 0));
    float s = (float)size;
    GraphicsPath p;
    RoundPath(p, RectF(s * 0.04f, s * 0.04f, s * 0.92f, s * 0.92f), s * 0.24f);
    LinearGradientBrush gb(PointF(0, 0), PointF(s, s), ColorOf(0xFF4FA3), ColorOf(0x4A90FF));
    SetStudioGradient(gb);
    g.FillPath(&gb, &p);
    // three linked dots = a hub
    Pen lp(Color(255, 255, 255), s * 0.045f);
    PointF c(s * 0.5f, s * 0.5f), a(s * 0.5f, s * 0.26f), b(s * 0.28f, s * 0.68f), d(s * 0.72f, s * 0.68f);
    g.DrawLine(&lp, c, a);
    g.DrawLine(&lp, c, b);
    g.DrawLine(&lp, c, d);
    SolidBrush wb(Color(255, 255, 255));
    float r1 = s * 0.075f, r2 = s * 0.11f;
    g.FillEllipse(&wb, c.X - r2, c.Y - r2, r2 * 2, r2 * 2);
    g.FillEllipse(&wb, a.X - r1, a.Y - r1, r1 * 2, r1 * 2);
    g.FillEllipse(&wb, b.X - r1, b.Y - r1, r1 * 2, r1 * 2);
    g.FillEllipse(&wb, d.X - r1, d.Y - r1, r1 * 2, r1 * 2);
    HICON icon = nullptr;
    bmp.GetHICON(&icon);
    return icon;
}
