static Bitmap* g_iconBmp[ARRAYSIZE(kIcons)] = {nullptr};

static void LoadIcons() {
    for (size_t i = 0; i < ARRAYSIZE(kIcons); i++) {
        IStream* stream = SHCreateMemStream(kIcons[i].data, kIcons[i].size);
        if (!stream) continue;
        Bitmap* src = Bitmap::FromStream(stream);
        if (src && src->GetLastStatus() == Ok) {
            int w = src->GetWidth(), h = src->GetHeight();
            Bitmap* copy = new Bitmap(w, h, PixelFormat32bppARGB);
            Graphics gg(copy);
            gg.DrawImage(src, 0, 0, w, h);
            g_iconBmp[i] = copy;
        }
        delete src;
        stream->Release();
    }
}

static Bitmap* FindIcon(const char* name) {
    char key[64];
    strncpy(key, name, sizeof(key) - 1);
    key[sizeof(key) - 1] = 0;
    for (char* p = key; *p; p++)
        if (*p == '-') *p = '_';
    for (size_t i = 0; i < ARRAYSIZE(kIcons); i++)
        if (strcmp(kIcons[i].name, key) == 0) return g_iconBmp[i];
    return nullptr;
}

