// Deletes a folder, but only if it is inside `root`.
static bool DeleteTreeUnder(const std::wstring& path, const std::wstring& root) {
    if (!IsDir(path)) return true;
    if (path.size() <= root.size() + 1 || StrCmpNIW(path.c_str(), root.c_str(), (int)root.size()) != 0) return false;
    if (path[root.size()] != L'\\') return false;
    std::wstring buf = path;
    buf.push_back(L'\0');  // SHFileOperation needs a double-null terminated list
    SHFILEOPSTRUCTW op;
    ZeroMemory(&op, sizeof(op));
    op.wFunc = FO_DELETE;
    op.pFrom = buf.c_str();
    op.fFlags = FOF_NOCONFIRMATION | FOF_NOERRORUI | FOF_SILENT;
    return SHFileOperationW(&op) == 0 && !op.fAnyOperationsAborted;
}

static bool Sha256File(const std::wstring& path, std::string& hex) {
    HANDLE f = CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ, nullptr, OPEN_EXISTING,
                           FILE_FLAG_SEQUENTIAL_SCAN, nullptr);
    if (f == INVALID_HANDLE_VALUE) return false;
    BCRYPT_ALG_HANDLE alg = nullptr;
    BCRYPT_HASH_HANDLE h = nullptr;
    bool ok = false;
    if (BCRYPT_SUCCESS(BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, nullptr, 0)) &&
        BCRYPT_SUCCESS(BCryptCreateHash(alg, &h, nullptr, 0, nullptr, 0, 0))) {
        std::vector<BYTE> buf(1 << 20);
        DWORD n = 0;
        ok = true;
        while (ReadFile(f, buf.data(), (DWORD)buf.size(), &n, nullptr) && n > 0)
            if (!BCRYPT_SUCCESS(BCryptHashData(h, buf.data(), n, 0))) { ok = false; break; }
        BYTE dig[32];
        if (ok && BCRYPT_SUCCESS(BCryptFinishHash(h, dig, 32, 0))) {
            static const char* hx = "0123456789abcdef";
            hex.clear();
            for (int i = 0; i < 32; i++) {
                hex += hx[dig[i] >> 4];
                hex += hx[dig[i] & 15];
            }
        } else ok = false;
    }
    if (h) BCryptDestroyHash(h);
    if (alg) BCryptCloseAlgorithmProvider(alg, 0);
    CloseHandle(f);
    return ok;
}

// Windows 10 1803+ ships tar.exe (bsdtar) which also unpacks .zip files.
static bool ExtractZip(const std::wstring& zip, const std::wstring& dest) {
    wchar_t sys[MAX_PATH];
    if (!GetSystemDirectoryW(sys, MAX_PATH)) return false;
    std::wstring tar = std::wstring(sys) + L"\\tar.exe";
    if (!IsFile(tar)) return false;
    SHCreateDirectoryExW(nullptr, dest.c_str(), nullptr);
    std::wstring cmd = L"\"" + tar + L"\" -xf \"" + zip + L"\" -C \"" + dest + L"\"";
    std::vector<wchar_t> cl(cmd.begin(), cmd.end());
    cl.push_back(0);
    STARTUPINFOW si;
    ZeroMemory(&si, sizeof(si));
    si.cb = sizeof(si);
    PROCESS_INFORMATION pi;
    if (!CreateProcessW(nullptr, cl.data(), nullptr, nullptr, FALSE, CREATE_NO_WINDOW, nullptr, nullptr, &si, &pi))
        return false;
    bool ok = WaitForSingleObject(pi.hProcess, 10 * 60 * 1000) == WAIT_OBJECT_0;
    DWORD code = 1;
    if (ok) GetExitCodeProcess(pi.hProcess, &code);
    CloseHandle(pi.hThread);
    CloseHandle(pi.hProcess);
    return ok && code == 0;
}

// Finds `name` (or, when empty, the first .exe) in dir, up to `depth` levels deep.
static std::wstring FindExe(const std::wstring& dir, const std::wstring& name, int depth) {
    WIN32_FIND_DATAW fd;
    HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
    if (h == INVALID_HANDLE_VALUE) return L"";
    std::vector<std::wstring> subs;
    std::wstring found;
    do {
        std::wstring n = fd.cFileName;
        if (n == L"." || n == L"..") continue;
        if (fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) {
            if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_REPARSE_POINT)) subs.push_back(n);
        } else if (name.empty()) {
            if (n.size() > 4 && _wcsicmp(n.c_str() + n.size() - 4, L".exe") == 0 && found.empty()) found = dir + L"\\" + n;
        } else if (_wcsicmp(n.c_str(), name.c_str()) == 0) {
            found = dir + L"\\" + n;
        }
    } while (found.empty() && FindNextFileW(h, &fd));
    FindClose(h);
    if (!found.empty()) return found;
    if (depth > 0)
        for (const std::wstring& s : subs) {
            std::wstring r = FindExe(dir + L"\\" + s, name, depth - 1);
            if (!r.empty()) return r;
        }
    return L"";
}

// If dir holds exactly one folder and no files (zip with a top-level folder), returns that folder.
static std::wstring FlattenRoot(const std::wstring& dir) {
    WIN32_FIND_DATAW fd;
    HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
    if (h == INVALID_HANDLE_VALUE) return dir;
    int files = 0, dirs = 0;
    std::wstring only;
    do {
        std::wstring n = fd.cFileName;
        if (n == L"." || n == L"..") continue;
        if (fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) { dirs++; only = n; }
        else files++;
    } while (FindNextFileW(h, &fd));
    FindClose(h);
    return (files == 0 && dirs == 1) ? dir + L"\\" + only : dir;
}

