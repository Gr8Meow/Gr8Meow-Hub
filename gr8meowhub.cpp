static void StartFetch() {
    if (g_fetching || g_jobRunning) return;
    g_fetching = true;
    g_fetchHub = g_s.checkUpdates;
    g_focusId.clear();
    g_footer = L"Checking for updates...";
    HANDLE h = CreateThread(nullptr, 0, FetchThread, nullptr, 0, nullptr);
    if (!h) {
        g_fetching = false;
        g_footer = L"Could not start the check";
    } else {
        CloseHandle(h);
        SetTimer(g_main, 1, 33, nullptr);
    }
    InvalidateUI();
}

static void StartJob(Job* j) {
    HANDLE h = CreateThread(nullptr, 0, JobThread, j, 0, nullptr);
    if (!h) {
        delete j;
        g_jobRunning = false;
        return;
    }
    CloseHandle(h);
}

static bool StartAppJob(int i) {
    if (i < 0 || i >= (int)g_apps.size() || g_jobRunning || g_fetching) return false;
    App& a = g_apps[i];
    if (!a.relOk) return false;
    bool zip = EndsWithI(a.assetName, ".zip");
    if (!zip && !EndsWithI(a.assetName, ".exe")) {
        a.status = L"Unsupported release file";
        a.failed = true;
        return false;
    }
    Job* j = new Job();
    j->kind = 0;
    j->id = a.def.id;
    j->tag = a.latest;
    j->url = FromUtf8(a.assetUrl);
    j->shaUrl = FromUtf8(a.shaUrl);
    j->assetName = FromUtf8(a.assetName);
    j->exeName = FromUtf8(a.def.exe);
    j->appName = FromUtf8(a.def.name);
    j->isZip = zip;
    a.busy = true;
    a.failed = false;
    a.progress = 0;
    a.status = L"Starting...";
    g_jobRunning = true;
    g_jobKind = 0;
    g_jobId = a.def.id;
    StartJob(j);
    InvalidateUI();
    return true;
}

static void NextUpdateAll() {
    for (size_t i = 0; i < g_apps.size(); i++)
        if (UpdateAvail(g_apps[i]) && !g_apps[i].failed && StartAppJob((int)i)) return;
    g_updAll = false;
}

static bool HubUpdateVisible() { return g_hub.ok && g_hub.newer && g_hub.tag != g_s.skipTag; }

