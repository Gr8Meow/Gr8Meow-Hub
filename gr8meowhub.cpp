// "v1.2.3" -> compare numerically. Returns -1, 0, 1.
static void ParseVer(const std::string& s, std::vector<long>& v) {
    size_t i = 0;
    if (i < s.size() && (s[i] == 'v' || s[i] == 'V')) i++;
    long cur = -1;
    for (; i < s.size(); i++) {
        char c = s[i];
        if (c >= '0' && c <= '9') {
            if (cur < 0) cur = 0;
            cur = cur * 10 + (c - '0');
            if (cur > 1000000) cur = 1000000;
        } else if (c == '.') {
            v.push_back(cur < 0 ? 0 : cur);
            cur = -1;
        } else {
            break;
        }
    }
    if (cur >= 0) v.push_back(cur);
}
static int CmpVer(const std::string& a, const std::string& b) {
    std::vector<long> x, y;
    ParseVer(a, x);
    ParseVer(b, y);
    size_t n = max(x.size(), y.size());
    for (size_t i = 0; i < n; i++) {
        long p = i < x.size() ? x[i] : 0, q = i < y.size() ? y[i] : 0;
        if (p != q) return p < q ? -1 : 1;
    }
    return 0;
}
static std::wstring DisplayVer(const std::string& tag) {
    std::string t = tag;
    if (!t.empty() && (t[0] == 'v' || t[0] == 'V')) t.erase(0, 1);
    return L"v" + FromUtf8(t);
}

// ===================================================================== JSON ===
struct JV {
    enum T { Null, Bool, Num, Str, Arr, Obj } t = Null;
    bool b = false;
    double n = 0;
    std::string s;
    std::vector<JV> a;
    std::vector<std::pair<std::string, JV>> o;
    const JV* get(const char* k) const {
        if (t != Obj) return nullptr;
        for (const auto& p : o)
            if (p.first == k) return &p.second;
        return nullptr;
    }
    std::string str(const char* k) const {
        const JV* v = get(k);
        return (v && v->t == Str) ? v->s : std::string();
    }
};
struct JP {
    const char* p;
    const char* e;
};
static void JSkip(JP& j) {
    while (j.p < j.e && (*j.p == ' ' || *j.p == '\t' || *j.p == '\n' || *j.p == '\r')) j.p++;
}
static int HexVal(char h) {
    if (h >= '0' && h <= '9') return h - '0';
    if (h >= 'a' && h <= 'f') return h - 'a' + 10;
    if (h >= 'A' && h <= 'F') return h - 'A' + 10;
    return -1;
}
static void AppendUtf8(std::string& o, unsigned cp) {
    if (cp < 0x80) o += (char)cp;
    else if (cp < 0x800) { o += (char)(0xC0 | (cp >> 6)); o += (char)(0x80 | (cp & 0x3F)); }
    else if (cp < 0x10000) { o += (char)(0xE0 | (cp >> 12)); o += (char)(0x80 | ((cp >> 6) & 0x3F)); o += (char)(0x80 | (cp & 0x3F)); }
    else { o += (char)(0xF0 | (cp >> 18)); o += (char)(0x80 | ((cp >> 12) & 0x3F)); o += (char)(0x80 | ((cp >> 6) & 0x3F)); o += (char)(0x80 | (cp & 0x3F)); }
}
static bool JHex4(JP& j, unsigned& cp) {
    if (j.e - j.p < 4) return false;
    cp = 0;
    for (int i = 0; i < 4; i++) {
        int h = HexVal(*j.p++);
        if (h < 0) return false;
        cp = (cp << 4) | (unsigned)h;
    }
    return true;
}
static bool JStr(JP& j, std::string& out) {
    if (j.p >= j.e || *j.p != '"') return false;
    j.p++;
    while (j.p < j.e) {
        char c = *j.p++;
        if (c == '"') return true;
        if (c != '\\') { out += c; continue; }
        if (j.p >= j.e) return false;
        char d = *j.p++;
        switch (d) {
            case 'n': out += '\n'; break;
            case 't': out += '\t'; break;
            case 'r': out += '\r'; break;
            case 'b': out += '\b'; break;
            case 'f': out += '\f'; break;
            case '/': case '\\': case '"': out += d; break;
            case 'u': {
                unsigned cp;
                if (!JHex4(j, cp)) return false;
                if (cp >= 0xD800 && cp < 0xDC00 && j.e - j.p >= 6 && j.p[0] == '\\' && j.p[1] == 'u') {
                    JP k = {j.p + 2, j.e};
                    unsigned lo;
                    if (JHex4(k, lo) && lo >= 0xDC00 && lo < 0xE000) {
                        cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00);
                        j.p = k.p;
                    }
                }
                AppendUtf8(out, cp);
                break;
            }
            default: return false;
        }
    }
    return false;
}
static bool JVal(JP& j, JV& v, int depth) {
    if (depth > 24) return false;
    JSkip(j);
    if (j.p >= j.e) return false;
    char c = *j.p;
    if (c == '{') {
        j.p++;
        v.t = JV::Obj;
        JSkip(j);
        if (j.p < j.e && *j.p == '}') { j.p++; return true; }
        for (;;) {
            JSkip(j);
            std::string key;
            if (!JStr(j, key)) return false;
            JSkip(j);
            if (j.p >= j.e || *j.p != ':') return false;
            j.p++;
            JV child;
            if (!JVal(j, child, depth + 1)) return false;
            if (v.o.size() < 2000) v.o.emplace_back(std::move(key), std::move(child));
            JSkip(j);
            if (j.p >= j.e) return false;
            if (*j.p == ',') { j.p++; continue; }
            if (*j.p == '}') { j.p++; return true; }
            return false;
        }
    }
    if (c == '[') {
        j.p++;
        v.t = JV::Arr;
        JSkip(j);
        if (j.p < j.e && *j.p == ']') { j.p++; return true; }
        for (;;) {
            JV child;
            if (!JVal(j, child, depth + 1)) return false;
            if (v.a.size() < 2000) v.a.push_back(std::move(child));
            JSkip(j);
            if (j.p >= j.e) return false;
            if (*j.p == ',') { j.p++; continue; }
            if (*j.p == ']') { j.p++; return true; }
            return false;
        }
    }
    if (c == '"') {
        v.t = JV::Str;
        return JStr(j, v.s);
    }
    if (j.e - j.p >= 4 && strncmp(j.p, "true", 4) == 0) { j.p += 4; v.t = JV::Bool; v.b = true; return true; }
    if (j.e - j.p >= 5 && strncmp(j.p, "false", 5) == 0) { j.p += 5; v.t = JV::Bool; v.b = false; return true; }
    if (j.e - j.p >= 4 && strncmp(j.p, "null", 4) == 0) { j.p += 4; v.t = JV::Null; return true; }
    std::string num;
    while (j.p < j.e && (strchr("+-0123456789.eE", *j.p) != nullptr) && num.size() < 40) num += *j.p++;
    if (num.empty()) return false;
    v.t = JV::Num;
    v.n = atof(num.c_str());
    return true;
}
static bool ParseJson(const std::string& text, JV& out) {
    JP j = {text.data(), text.data() + text.size()};
    if (text.size() >= 3 && (unsigned char)text[0] == 0xEF && (unsigned char)text[1] == 0xBB && (unsigned char)text[2] == 0xBF)
        j.p += 3;
    if (!JVal(j, out, 0)) return false;
    return true;
}

// ===================================================================== HTTP ===
typedef bool (*SinkFn)(const char* data, DWORD n, void* ctx);

static bool HostAllowed(const std::wstring& h) {
    static const wchar_t* ok[] = {L"api.github.com", L"github.com", L"raw.githubusercontent.com",
                                  L"objects.githubusercontent.com", L"release-assets.githubusercontent.com"};
    for (const wchar_t* a : ok)
        if (_wcsicmp(h.c_str(), a) == 0) return true;
    return false;
}

// HTTPS only, GitHub hosts only (redirects stay on HTTPS).
static bool Http(const std::wstring& url, SinkFn sink, void* ctx, DWORD* statusOut, ULONGLONG* totalOut) {
    if (statusOut) *statusOut = 0;
    if (url.compare(0, 8, L"https://") != 0) return false;
    size_t slash = url.find(L'/', 8);
    std::wstring host = url.substr(8, slash == std::wstring::npos ? std::wstring::npos : slash - 8);
    std::wstring path = slash == std::wstring::npos ? L"/" : url.substr(slash);
    if (!HostAllowed(host)) return false;

    bool ok = false;
    HINTERNET s = WinHttpOpen(L"Gr8MeowHub/" L"1", WINHTTP_ACCESS_TYPE_DEFAULT_PROXY, WINHTTP_NO_PROXY_NAME,
                              WINHTTP_NO_PROXY_BYPASS, 0);
    if (!s) return false;
    WinHttpSetTimeouts(s, 10000, 10000, 30000, 60000);
    HINTERNET c = WinHttpConnect(s, host.c_str(), INTERNET_DEFAULT_HTTPS_PORT, 0);
    HINTERNET r = c ? WinHttpOpenRequest(c, L"GET", path.c_str(), nullptr, WINHTTP_NO_REFERER,
                                         WINHTTP_DEFAULT_ACCEPT_TYPES, WINHTTP_FLAG_SECURE)
                    : nullptr;
    if (r) {
        const wchar_t* hdr = L"Accept: application/vnd.github+json, application/octet-stream, */*\r\n";
        if (WinHttpSendRequest(r, hdr, (DWORD)-1L, WINHTTP_NO_REQUEST_DATA, 0, 0, 0) && WinHttpReceiveResponse(r, nullptr)) {
            DWORD st = 0, sz = sizeof(st);
            WinHttpQueryHeaders(r, WINHTTP_QUERY_STATUS_CODE | WINHTTP_QUERY_FLAG_NUMBER, WINHTTP_HEADER_NAME_BY_INDEX,
                                &st, &sz, WINHTTP_NO_HEADER_INDEX);
            if (statusOut) *statusOut = st;
            if (st == 200) {
                if (totalOut) {
                    wchar_t lb[32];
                    DWORD ls = sizeof(lb);
                    if (WinHttpQueryHeaders(r, WINHTTP_QUERY_CONTENT_LENGTH, WINHTTP_HEADER_NAME_BY_INDEX, lb, &ls,
                                            WINHTTP_NO_HEADER_INDEX))
                        *totalOut = (ULONGLONG)_wtoi64(lb);
                }
                ok = true;
                std::vector<char> buf(65536);
                for (;;) {
                    DWORD avail = 0;
                    if (!WinHttpQueryDataAvailable(r, &avail)) { ok = false; break; }
                    if (avail == 0) break;
                    DWORD n = 0, want = min<DWORD>(avail, (DWORD)buf.size());
                    if (!WinHttpReadData(r, buf.data(), want, &n)) { ok = false; break; }
                    if (n == 0) break;
                    if (!sink(buf.data(), n, ctx)) { ok = false; break; }
                }
            }
        }
    }
    if (r) WinHttpCloseHandle(r);
    if (c) WinHttpCloseHandle(c);
    WinHttpCloseHandle(s);
    return ok;
}

struct StrSink {
    std::string data;
    size_t max;
};
static bool StrSinkFn(const char* d, DWORD n, void* c) {
    StrSink* s = (StrSink*)c;
    if (s->data.size() + n > s->max) return false;
    s->data.append(d, n);
    return true;
}
static bool HttpGetString(const std::wstring& url, std::string& out, DWORD* status, size_t maxBytes) {
    StrSink s;
    s.max = maxBytes;
    bool ok = Http(url, StrSinkFn, &s, status, nullptr);
    if (ok) out = std::move(s.data);
    return ok;
}

struct FileSink {
    HANDLE h = INVALID_HANDLE_VALUE;
    ULONGLONG got = 0, total = 0;
    int lastPct = -2;
};
static bool FileSinkFn(const char* d, DWORD n, void* c) {
    FileSink* f = (FileSink*)c;
    DWORD w = 0;
    if (!WriteFile(f->h, d, n, &w, nullptr) || w != n) return false;
    f->got += n;
    if (f->got > 800ull * 1024 * 1024) return false;  // sanity limit
    int pct = f->total ? (int)(f->got * 100 / f->total) : -1;
    if (pct != f->lastPct) {
        f->lastPct = pct;
        PostMessageW(g_main, WM_PROGRESS, 0, (LPARAM)pct);
    }
    return true;
}

